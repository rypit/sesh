#[derive(Clone, Default, PartialEq, Eq)]
pub struct Secrets {
    values: BTreeMap<String, String>,
}

impl fmt::Debug for Secrets {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("Secrets")
            .field("keys", &self.values.keys().collect::<Vec<_>>())
            .finish()
    }
}

impl Secrets {
    pub fn parse(text: &str) -> Result<Self> {
        let mut values = BTreeMap::new();
        for (n, line) in text.lines().enumerate() {
            let line = line.trim();
            if line.is_empty() || line.starts_with('#') {
                continue;
            }
            let Some((k, v)) = line.split_once('=') else {
                bail!("secrets.env line {} is not KEY=value", n + 1);
            };
            values.insert(k.trim().to_string(), v.trim().to_string());
        }
        Ok(Secrets { values })
    }

    pub fn render(&self) -> String {
        let mut out = String::from("# Generated by sesh. Do not commit or share.\n");
        for (k, v) in &self.values {
            out.push_str(&format!("{k}={v}\n"));
        }
        out
    }

    /// Every value, for redaction (never printed).
    pub fn values(&self) -> Vec<String> {
        self.values.values().cloned().collect()
    }

    pub fn get(&self, key: &str) -> Option<&str> {
        self.values.get(key).map(String::as_str)
    }

    /// Every agent runtime's router key, as (name, value).
    pub fn agent_router_keys(&self) -> Vec<(String, String)> {
        self.values
            .iter()
            .filter(|(k, _)| k.starts_with("AGENT_") && k.ends_with("_ROUTER_KEY"))
            .map(|(k, v)| (k.clone(), v.clone()))
            .collect()
    }

    pub fn remove(&mut self, key: &str) {
        self.values.remove(key);
    }

    pub fn set(&mut self, key: &str, value: &str) {
        self.values.insert(key.to_string(), value.to_string());
    }

    /// Generates every value in [`GENERATED`] that is missing. Returns the
    /// names generated (never the values).
    pub fn fill_missing(&mut self) -> Result<Vec<&'static str>> {
        let mut made = Vec::new();
        for key in GENERATED {
            if !self.values.contains_key(key) {
                self.values.insert(key.to_string(), generate(key)?);
                made.push(key);
            }
        }
        Ok(made)
    }

    pub fn load(dir: &Path) -> Result<Self> {
        let path = dir.join(FILE_NAME);
        if !path.exists() {
            return Ok(Secrets::default());
        }
        let text = std::fs::read_to_string(&path)
            .with_context(|| format!("can't read {}", path.display()))?;
        Self::parse(&text)
    }

    /// Writes a 0600 temp file in `dir`, then renames it over
    /// `secrets.env`, so a crash or full disk never leaves a truncated
    /// file and the values are never readable by others, even briefly.
    pub fn save(&self, dir: &Path) -> Result<()> {
        use std::io::Write;
        let path = dir.join(FILE_NAME);
        let tmp = dir.join(format!(".{FILE_NAME}.tmp-{}", std::process::id()));
        let written = (|| -> Result<()> {
            let mut f = create_private(&tmp)?;
            f.write_all(self.render().as_bytes())?;
            f.sync_all()?;
            Ok(())
        })();
        if let Err(e) = written {
            let _ = std::fs::remove_file(&tmp);
            return Err(e.context(format!("can't write {}", path.display())));
        }
        if let Err(e) = std::fs::rename(&tmp, &path) {
            let _ = std::fs::remove_file(&tmp);
            return Err(anyhow::Error::new(e).context(format!("can't replace {}", path.display())));
        }
        Ok(())
    }
}

/// 32 random bytes, URL-safe base64 without padding.
pub fn random_token() -> Result<String> {
    let mut bytes = [0u8; 32];
    getrandom::fill(&mut bytes).map_err(|e| anyhow::anyhow!("OS random source failed: {e}"))?;
    Ok(base64::engine::general_purpose::URL_SAFE_NO_PAD.encode(bytes))
}

/// Creates `dir` if needed and restricts it to the owner.
pub fn ensure_private_dir(dir: &Path) -> Result<()> {
    std::fs::create_dir_all(dir).with_context(|| format!("can't create {}", dir.display()))?;
    restrict(dir, 0o700)
}

#[cfg(unix)]
fn restrict(path: &Path, mode: u32) -> Result<()> {
    use std::os::unix::fs::PermissionsExt;
    std::fs::set_permissions(path, std::fs::Permissions::from_mode(mode))?;
    Ok(())
}

/// Creates `path` (replacing a stale one) readable by the owner only.
#[cfg(unix)]
fn create_private(path: &Path) -> Result<std::fs::File> {
    use std::os::unix::fs::OpenOptionsExt;
    let _ = std::fs::remove_file(path);
    let f = std::fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .mode(0o600)
        .open(path)?;
    // The umask can only narrow the mode; set it exactly.
    restrict(path, 0o600)?;
    Ok(f)
}

#[cfg(not(unix))]
fn create_private(path: &Path) -> Result<std::fs::File> {
    let _ = std::fs::remove_file(path);
    Ok(std::fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(path)?)
}

#[cfg(not(unix))]
fn restrict(_path: &Path, _mode: u32) -> Result<()> {
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn tempdir(name: &str) -> std::path::PathBuf {
        let d = std::env::temp_dir().join(format!("sesh-secrets-{name}-{}", std::process::id()));
        ensure_private_dir(&d).unwrap();
        d
    }

    #[test]
    fn fills_only_missing_and_keeps_existing() {
        let mut s = Secrets::default();
        s.set("POSTGRES_PASSWORD", "keep");
        let made = s.fill_missing().unwrap();
        assert!(!made.contains(&"POSTGRES_PASSWORD"));
        assert_eq!(made.len(), GENERATED.len() - 1);
        assert_eq!(s.get("POSTGRES_PASSWORD"), Some("keep"));
        assert!(s.fill_missing().unwrap().is_empty());
    }

    #[test]
    fn tokens_are_random_and_url_safe() {
        let a = random_token().unwrap();
        let b = random_token().unwrap();
        assert_ne!(a, b);
        assert_eq!(a.len(), 43);
        assert!(
            a.chars()
                .all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_')
        );
    }

    #[test]
    fn debug_never_shows_values() {
        let mut s = Secrets::default();
        s.set("LITELLM_MASTER_KEY", "super-secret-value");
        let shown = format!("{s:?}");
        assert!(shown.contains("LITELLM_MASTER_KEY"));
        assert!(!shown.contains("super-secret-value"));
    }

    #[test]
    fn round_trips_and_is_private_on_disk() {
        let dir = tempdir("rt");
        let mut s = Secrets::default();
        s.fill_missing().unwrap();
        s.save(&dir).unwrap();
        assert_eq!(Secrets::load(&dir).unwrap(), s);
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            let mode = std::fs::metadata(dir.join(FILE_NAME))
                .unwrap()
                .permissions()
                .mode();
            assert_eq!(mode & 0o777, 0o600);
            let dmode = std::fs::metadata(&dir).unwrap().permissions().mode();
            assert_eq!(dmode & 0o777, 0o700);
        }
    }

    #[test]
    fn save_replaces_atomically_and_leaves_no_temp_file() {
        let dir = tempdir("atomic");
        let path = dir.join(FILE_NAME);
        // An existing file with loose permissions is replaced, not rewritten.
        std::fs::write(&path, "OLD=1\n").unwrap();
        #[cfg(unix)]
        restrict(&path, 0o644).unwrap();
        #[cfg(unix)]
        let old_inode = {
            use std::os::unix::fs::MetadataExt;
            std::fs::metadata(&path).unwrap().ino()
        };
        let mut s = Secrets::default();
        s.set("A", "b");
        s.save(&dir).unwrap();
        assert_eq!(Secrets::load(&dir).unwrap(), s);
        #[cfg(unix)]
        {
            use std::os::unix::fs::{MetadataExt, PermissionsExt};
            let meta = std::fs::metadata(&path).unwrap();
            assert_eq!(meta.permissions().mode() & 0o777, 0o600);
            // Renamed over the target: a new file, never truncated in place.
            assert_ne!(meta.ino(), old_inode);
        }
        let names: Vec<_> = std::fs::read_dir(&dir)
            .unwrap()
            .map(|e| e.unwrap().file_name().into_string().unwrap())
            .collect();
        assert_eq!(names, vec![FILE_NAME.to_string()]);
    }

    #[test]
    fn rejects_malformed_lines() {
        assert!(Secrets::parse("NOEQUALS\n").is_err());
        assert!(Secrets::parse("# comment\n\nA=b\n").is_ok());
    }

    #[test]
    fn infisical_values_have_their_formats() {
        let mut s = Secrets::default();
        s.fill_missing().unwrap();
        let k = s.get("INFISICAL_ENCRYPTION_KEY").unwrap();
        assert_eq!(k.len(), 32);
        assert!(k.chars().all(|c| c.is_ascii_hexdigit()));
        let a = s.get("INFISICAL_AUTH_SECRET").unwrap();
        assert_eq!(
            base64::engine::general_purpose::STANDARD
                .decode(a)
                .unwrap()
                .len(),
            32
        );
        assert!((6..=32).contains(&s.get("INFISICAL_SETUP_TOKEN").unwrap().len()));
    }
}
