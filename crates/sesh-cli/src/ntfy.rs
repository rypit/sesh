//! The approval channels' config (specs/004 research.md R3, specs/005
//! R2): ntfy with `deny-all`. The gateway may only publish, to sesh's
//! topics; each reader may only read the topics listed for it: a user
//! reads their own and the Household's, and `person` reads the
//! Household's. The bcrypt hashes go in a generated `server.yml` (a `$`
//! in an env file would be interpolated).

use anyhow::Result;
use std::path::Path;

pub const FILE: &str = "ntfy-server.yml";
pub const GATEWAY_USER: &str = "sesh-gateway";
pub const PERSON_USER: &str = "person";

/// One ntfy account that may read some topics.
pub struct Reader {
    pub user: String,
    pub password: String,
    pub topics: Vec<String>,
}

/// The ntfy user for a sesh user.
pub fn reader_name(user: &str) -> String {
    format!("u-{user}")
}

fn access_lines(gateway_topics: &[String], readers: &[Reader]) -> Vec<String> {
    let mut lines: Vec<String> = gateway_topics
        .iter()
        .map(|t| format!("  - \"{GATEWAY_USER}:{t}:wo\""))
        .collect();
    for r in readers {
        for t in &r.topics {
            lines.push(format!("  - \"{}:{t}:ro\"", r.user));
        }
    }
    lines
}

pub fn server_yml(
    gateway_topics: &[String],
    gateway_hash: &str,
    readers: &[(String, String, Vec<String>)],
) -> String {
    let rs: Vec<Reader> = readers
        .iter()
        .map(|(u, _, t)| Reader {
            user: u.clone(),
            password: String::new(),
            topics: t.clone(),
        })
        .collect();
    let mut s = String::from(
        "# Generated by `sesh up` (specs/004, 005). Do not edit.\n\
listen-http: \":80\"\n\
base-url: \"http://127.0.0.1:8090\"\n\
auth-file: \"/var/lib/ntfy/auth.db\"\n\
auth-default-access: \"deny-all\"\n\
enable-login: true\n\
auth-users:\n",
    );
    s.push_str(&format!("  - \"{GATEWAY_USER}:{gateway_hash}:user\"\n"));
    for (u, h, _) in readers {
        s.push_str(&format!("  - \"{u}:{h}:user\"\n"));
    }
    s.push_str("auth-access:\n");
    for l in access_lines(gateway_topics, &rs) {
        s.push_str(&l);
        s.push('\n');
    }
    s
}

fn hash_in(text: &str, user: &str) -> Option<String> {
    let prefix = format!("  - \"{user}:");
    text.lines()
        .filter(|l| l.ends_with(":user\""))
        .find_map(|l| l.strip_prefix(&prefix))
        .and_then(|rest| rest.strip_suffix(":user\""))
        .map(str::to_string)
}

/// Writes `<dir>/ntfy-server.yml` unless the current one already has the
/// same accounts, passwords and access. Returns whether it changed.
pub fn write_config(
    dir: &Path,
    gateway_topics: &[String],
    gateway_pw: &str,
    readers: &[Reader],
) -> Result<bool> {
    let path = dir.join(FILE);
    if let Ok(text) = std::fs::read_to_string(&path) {
        let verify = |user: &str, pw: &str| {
            hash_in(&text, user).is_some_and(|h| bcrypt::verify(pw, &h).unwrap_or(false))
        };
        let same_access = {
            let want = access_lines(gateway_topics, readers);
            let have: Vec<String> = text
                .lines()
                .skip_while(|l| *l != "auth-access:")
                .skip(1)
                .map(str::to_string)
                .collect();
            want == have
        };
        let users_now = text.lines().filter(|l| l.ends_with(":user\"")).count();
        if same_access
            && users_now == readers.len() + 1
            && verify(GATEWAY_USER, gateway_pw)
            && readers.iter().all(|r| verify(&r.user, &r.password))
        {
            return Ok(false);
        }
    }
    let g = bcrypt::hash(gateway_pw, 10)?;
    let mut hashed = Vec::new();
    for r in readers {
        hashed.push((
            r.user.clone(),
            bcrypt::hash(&r.password, 10)?,
            r.topics.clone(),
        ));
    }
    std::fs::write(&path, server_yml(gateway_topics, &g, &hashed))?;
    Ok(true)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn reader(user: &str, pw: &str, topics: &[&str]) -> Reader {
        Reader {
            user: user.into(),
            password: pw.into(),
            topics: topics.iter().map(|t| t.to_string()).collect(),
        }
    }

    #[test]
    fn writes_once_and_keeps_only_hashes() {
        let dir = std::env::temp_dir().join(format!("sesh-ntfy-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        let topics = vec!["hh".to_string(), "ana-t".to_string()];
        let readers = [
            reader("person", "person-pass-123", &["hh"]),
            reader("u-ana", "ana-pass-123", &["ana-t", "hh"]),
        ];
        assert!(write_config(&dir, &topics, "gw-pass-123", &readers).unwrap());
        let text = std::fs::read_to_string(dir.join(FILE)).unwrap();
        assert!(!text.contains("gw-pass-123") && !text.contains("ana-pass-123"));
        assert!(text.contains("auth-default-access: \"deny-all\""));
        assert!(
            text.contains("\"sesh-gateway:hh:wo\"") && text.contains("\"sesh-gateway:ana-t:wo\"")
        );
        assert!(
            text.contains("\"u-ana:ana-t:ro\"")
                && text.contains("\"u-ana:hh:ro\"")
                && text.contains("\"person:hh:ro\"")
        );
        assert!(
            !text.contains("\"person:ana-t"),
            "the household reader can't read Ana's topic"
        );
        assert!(
            !write_config(&dir, &topics, "gw-pass-123", &readers).unwrap(),
            "unchanged"
        );
        assert!(
            write_config(&dir, &topics[..1], "gw-pass-123", &readers[..1]).unwrap(),
            "a user removed"
        );
        assert!(
            write_config(&dir, &topics[..1], "other", &readers[..1]).unwrap(),
            "new password"
        );
    }
}
