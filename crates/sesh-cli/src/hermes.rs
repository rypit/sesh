//! Hermes Agent, the agent runtime (specs/009, ADR 0012). This is the one
//! module that knows how Hermes is configured and run: its `config.yaml`,
//! its credentials file and its Compose service.
//!
//! The runtime gets the gateway's tools and nothing else: its API server
//! platform lists only the gateway's MCP server, and every built-in
//! toolset is also disabled globally (research.md R2).

use anyhow::Result;
use serde_json::{Value, json};
use std::path::{Path, PathBuf};

pub const IMAGE: &str = "nousresearch/hermes-agent:v0.23.4@sha256:ef0650d523ee1b5ab32c779acabc446d9936869a9932591553688a62bcf0c42f";
pub const PORT: u16 = 8642;
/// The gateway's MCP server as Hermes names its toolset (`mcp-<server>`).
pub const GATEWAY_TOOLSET: &str = "mcp-sesh";

const TOOLSETS: &str = include_str!("hermes/toolsets.txt");

/// Every built-in toolset, from the reference copy.
pub fn builtin_toolsets() -> Vec<&'static str> {
    TOOLSETS
        .lines()
        .map(str::trim)
        .filter(|l| !l.is_empty() && !l.starts_with('#'))
        .collect()
}

pub fn service(agent: &str) -> String {
    format!("hermes-{agent}")
}

/// The gateway's alias on the agent's network (research.md R5).
pub fn gateway_alias(agent: &str) -> String {
    format!("gateway-agent-{agent}")
}

/// The pair networks (specs/009 research.md R6): with the gateway and
/// with the model router. Open WebUI reaches the runtime through the
/// gateway's chat listener (specs/010 R2), so there is no chat network.
pub fn networks(agent: &str) -> [String; 2] {
    [format!("agent-{agent}"), format!("agent-{agent}-model")]
}

/// The chat listener's address for an agent, as Open WebUI's connection.
pub fn chat_url(agent: &str) -> String {
    format!("http://{CHAT_ALIAS}:7003/agent/{agent}/v1")
}

/// The gateway's alias on the `chat` network (specs/010 R2).
pub const CHAT_ALIAS: &str = "gateway-chat";

/// sesh's memory provider plugin (specs/011), mounted read-only.
pub const PLUGIN: &str = "sesh_memory";
pub const PLUGIN_INIT: &str =
    include_str!("../../../deploy/hermes/plugins/sesh_memory/__init__.py");
pub const PLUGIN_YAML: &str =
    include_str!("../../../deploy/hermes/plugins/sesh_memory/plugin.yaml");

pub fn plugin_dir(dir: &Path) -> PathBuf {
    dir.join("agents").join("plugins").join(PLUGIN)
}

pub fn config_path(dir: &Path, agent: &str) -> PathBuf {
    dir.join("agents").join(agent).join("config.yaml")
}

pub fn env_path(dir: &Path, agent: &str) -> PathBuf {
    dir.join("agents").join(format!("{agent}.env"))
}

/// The runtime's `config.yaml`. JSON is YAML, so it's written as JSON.
/// It holds no secret: the token and keys come from the environment.
pub fn config(agent: &str) -> Value {
    json!({
        "model": {
            "provider": "custom",
            "base_url": "http://litellm:4000/v1",
            "default": crate::config::REQUIRED_ALIAS,
            // The agent's own router key, from its env file (research.md R3).
            "key_env": "SESH_ROUTER_KEY",
        },
        // Offer the gateway's tools directly, not behind Hermes's
        // tool-search bridge (research.md R2).
        "tools": {"tool_search": {"enabled": "off"}},
        // Side tasks use the main endpoint, never another provider.
        "auxiliary": {
            "vision": {"provider": "main"},
            "web_extract": {"provider": "main"},
            "compression": {"provider": "main"},
            "title_generation": {"provider": "main"},
            "session_search": {"provider": "main"},
            "curator": {"provider": "main"},
            "background_review": {"provider": "main"},
        },
        "mcp_servers": {
            "sesh": {
                "url": "http://gateway:7000/mcp",
                "headers": {"Authorization": "Bearer ${SESH_GATEWAY_TOKEN}"},
            }
        },
        "platform_toolsets": {"api_server": [GATEWAY_TOOLSET]},
        "agent": {"disabled_toolsets": builtin_toolsets()},
        // Hermes's own memory stays off; recall comes from sesh's plugin,
        // which calls only the gateway (specs/011 research.md R5).
        "memory": {"memory_enabled": false, "user_profile_enabled": false, "nudge_interval": 0, "provider": PLUGIN},
        "skills": {"creation_nudge_interval": 0},
        "gateway": {"api_server": {"model_name": agent}},
        "telemetry": {"shared_metrics": {"enabled": false, "send": false}},
        "updates": {"check": false},
        "auth": {"adopt_external_logins": false},
    })
}

pub fn config_text(agent: &str) -> String {
    let mut s = serde_json::to_string_pretty(&config(agent)).expect("json");
    s.push('\n');
    s
}

/// The runtime's credentials (research.md R7), for its 0600 env file, and
/// whether its memory plugin recalls (only with the `memory` connector).
pub fn env_text(gateway_token: &str, router_key: &str, api_key: &str, memory: bool) -> String {
    let memory = u8::from(memory);
    format!(
        "# Generated by `sesh up`. Do not share.\nSESH_GATEWAY_TOKEN={gateway_token}\nSESH_ROUTER_KEY={router_key}\nAPI_SERVER_KEY={api_key}\nSESH_MEMORY={memory}\n"
    )
}

/// The Compose service, for the generated overlay.
pub fn compose_service(agent: &str) -> String {
    let svc = service(agent);
    let [a, m] = networks(agent);
    format!(
        "  {svc}:\n    image: ${{SESH_HERMES_IMAGE:-{IMAGE}}}\n    command: [\"gateway\", \"run\"]\n    env_file: [\"${{SESH_DATA_DIR:?}}/agents/{agent}.env\"]\n    environment:\n      API_SERVER_ENABLED: \"true\"\n      API_SERVER_HOST: 0.0.0.0\n      API_SERVER_PORT: \"{PORT}\"\n      API_SERVER_MODEL_NAME: {agent}\n    volumes:\n      - {svc}-data:/opt/data\n      - ${{SESH_DATA_DIR:?}}/agents/{agent}/config.yaml:/opt/data/config.yaml:ro\n      - ${{SESH_DATA_DIR:?}}/agents/plugins/{PLUGIN}:/opt/data/plugins/{PLUGIN}:ro\n    networks: [{a}, {m}]\n    read_only: true\n    tmpfs: [\"/run:exec\", /tmp]\n    security_opt: [\"no-new-privileges:true\"]\n    cap_drop: [ALL]\n    cap_add: [CHOWN, DAC_OVERRIDE, FOWNER, SETGID, SETUID]\n    mem_limit: 2g\n    pids_limit: 512\n    healthcheck:\n      test: [\"CMD-SHELL\", \"curl -fsS http://127.0.0.1:{PORT}/health >/dev/null\"]\n      interval: 10s\n      timeout: 5s\n      retries: 60\n    depends_on:\n      gateway:\n        condition: service_healthy\n      litellm:\n        condition: service_healthy\n    restart: unless-stopped\n"
    )
}

/// Writes `path` with `text` only if it differs; returns whether it did.
pub fn write_if_changed(path: &Path, text: &str, private: bool) -> Result<bool> {
    if std::fs::read_to_string(path).ok().as_deref() == Some(text) {
        return Ok(false);
    }
    if let Some(p) = path.parent() {
        std::fs::create_dir_all(p)?;
    }
    let tmp = path.with_extension("tmp");
    std::fs::write(&tmp, text)?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let mode = if private { 0o600 } else { 0o644 };
        std::fs::set_permissions(&tmp, std::fs::Permissions::from_mode(mode))?;
    }
    #[cfg(not(unix))]
    let _ = private;
    std::fs::rename(&tmp, path)?;
    Ok(true)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn only_the_gateways_toolset_is_offered_and_every_builtin_is_off() {
        let c = config("household-agent");
        assert_eq!(c["platform_toolsets"]["api_server"], json!(["mcp-sesh"]));
        assert_eq!(
            c["platform_toolsets"].as_object().unwrap().len(),
            1,
            "no other platform"
        );
        let off: Vec<&str> = c["agent"]["disabled_toolsets"]
            .as_array()
            .unwrap()
            .iter()
            .map(|v| v.as_str().unwrap())
            .collect();
        for t in [
            "terminal",
            "file",
            "web",
            "search",
            "browser",
            "code_execution",
            "memory",
            "skills",
            "delegation",
            "cronjob",
            "image_gen",
            "computer_use",
            "connections",
            "vision",
        ] {
            assert!(off.contains(&t), "{t} must be disabled");
        }
        assert!(!off.contains(&GATEWAY_TOOLSET));
        let servers = c["mcp_servers"].as_object().unwrap();
        assert_eq!(servers.len(), 1, "the gateway is the only MCP server");
        assert_eq!(servers["sesh"]["url"], "http://gateway:7000/mcp");
        assert_eq!(c["memory"]["memory_enabled"], false);
        assert_eq!(
            c["memory"]["provider"], "sesh_memory",
            "recall through the gateway"
        );
        assert_eq!(c["tools"]["tool_search"]["enabled"], "off");
    }

    #[test]
    fn the_model_is_the_routers_alias_and_side_tasks_stay_on_it() {
        let c = config("a");
        assert_eq!(c["model"]["provider"], "custom");
        assert_eq!(c["model"]["base_url"], "http://litellm:4000/v1");
        assert_eq!(c["model"]["default"], "agent-main");
        assert_eq!(c["model"]["key_env"], "SESH_ROUTER_KEY");
        for (task, v) in c["auxiliary"].as_object().unwrap() {
            assert_eq!(v["provider"], "main", "{task}");
        }
        assert_eq!(c["gateway"]["api_server"]["model_name"], "a");
    }

    #[test]
    fn no_secret_value_is_in_the_config_or_the_compose_service() {
        let cfg = config_text("a");
        assert!(cfg.contains("${SESH_GATEWAY_TOKEN}"));
        let svc = compose_service("a");
        for s in [&cfg, &svc] {
            assert!(!s.contains("API_SERVER_KEY:"), "no key in {s}");
            assert!(!s.contains("SESH_ROUTER_KEY="), "no key in {s}");
        }
        let env = env_text("tok", "rk", "ak", true);
        assert!(env.contains("SESH_MEMORY=1\n"));
        assert!(env_text("tok", "rk", "ak", false).contains("SESH_MEMORY=0\n"));
        assert!(env.contains("SESH_GATEWAY_TOKEN=tok\n"));
        assert!(env.contains("SESH_ROUTER_KEY=rk\n"));
        assert!(env.contains("API_SERVER_KEY=ak\n"));
    }

    #[test]
    fn the_service_has_no_way_out_and_no_privilege_escalation() {
        let s = compose_service("h");
        assert!(s.contains("networks: [agent-h, agent-h-model]"));
        assert!(!s.contains("ports:"), "no published port");
        assert!(s.contains("no-new-privileges:true") && s.contains("cap_drop: [ALL]"));
        assert!(s.contains("read_only: true"));
        assert!(s.contains("/opt/data/config.yaml:ro"), "config read-only");
        assert!(
            s.contains("/opt/data/plugins/sesh_memory:ro"),
            "the plugin read-only"
        );
        assert!(s.contains("hermes-h-data:/opt/data"));
        assert!(s.contains(IMAGE) && IMAGE.contains("@sha256:"));
        assert!(s.contains("/health"));
    }

    #[test]
    fn the_toolset_reference_is_complete_enough() {
        let t = builtin_toolsets();
        assert!(t.len() >= 30, "{t:?}");
        let mut sorted = t.clone();
        sorted.sort();
        sorted.dedup();
        assert_eq!(sorted.len(), t.len(), "no duplicates");
    }

    #[test]
    fn writes_only_on_change_and_privately_when_asked() {
        let d = std::env::temp_dir().join(format!("sesh-hermes-{}", std::process::id()));
        let p = d.join("x.env");
        assert!(write_if_changed(&p, "a", true).unwrap());
        assert!(!write_if_changed(&p, "a", true).unwrap());
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            let m = std::fs::metadata(&p).unwrap().permissions().mode();
            assert_eq!(m & 0o777, 0o600);
        }
        assert!(write_if_changed(&p, "b", true).unwrap());
    }
}
