//! Postgres's login rules (specs/008 research.md R10, contracts/networks.md
//! "Database login rules"): each service's login is accepted only from
//! its own database network's address ranges, as Docker assigned them;
//! the superuser only over the local socket; everything else rejected.

use crate::layout::DB_LOGINS;
use anyhow::{Result, bail};

pub const DIR: &str = "postgres-conf";
pub const FILE: &str = "pg_hba.conf";

const HEADER: &str = "# Generated by `sesh up` from the networks' address ranges\n\
# (specs/008-network-isolation). Edits are overwritten.\n";
const LOCAL: &str = "local all all trust\n";
const REJECT: &str = "host all all all reject\n";

/// Before any range is known: administration over the local socket only.
pub fn initial() -> String {
    format!("{HEADER}{LOCAL}{REJECT}")
}

/// The rules for the given networks' subnets. `subnets(network)` returns
/// the ranges Docker assigned. An empty or unreadable range is an error
/// naming the network: no rule is ever widened to make up for it.
pub fn render(subnets: &dyn Fn(&str) -> Result<Vec<String>>) -> Result<String> {
    let mut out = String::from(HEADER);
    out.push_str(LOCAL);
    for (role, db, network) in DB_LOGINS {
        let ranges = match subnets(network) {
            Ok(r) if !r.is_empty() => r,
            _ => bail!(
                "can't read the address range of sesh_{network}; database logins stay refused"
            ),
        };
        for r in ranges {
            if !valid_cidr(&r) {
                bail!(
                    "sesh_{network} has an unexpected address range {r:?}; database logins stay refused"
                );
            }
            out.push_str(&format!("host {db} {role} {r} scram-sha-256\n"));
        }
    }
    out.push_str(REJECT);
    Ok(out)
}

/// An IPv4 or IPv6 network in CIDR form, nothing else (it goes into a
/// config file).
fn valid_cidr(s: &str) -> bool {
    let Some((addr, len)) = s.split_once('/') else {
        return false;
    };
    let Ok(len) = len.parse::<u8>() else {
        return false;
    };
    match addr.parse::<std::net::IpAddr>() {
        Ok(std::net::IpAddr::V4(_)) => len <= 32,
        Ok(std::net::IpAddr::V6(_)) => len <= 128,
        Err(_) => false,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn ranges(n: &str) -> Result<Vec<String>> {
        let i = DB_LOGINS.iter().position(|(_, _, x)| *x == n).unwrap();
        Ok(vec![format!("172.{}.0.0/16", 30 + i)])
    }

    #[test]
    fn initial_rules_allow_only_local_administration() {
        let r = initial();
        let lines: Vec<&str> = r.lines().filter(|l| !l.starts_with('#')).collect();
        assert_eq!(
            lines,
            vec!["local all all trust", "host all all all reject"]
        );
    }

    #[test]
    fn each_login_is_bound_to_its_own_network_and_everything_else_is_rejected() {
        let r = render(&ranges).unwrap();
        let lines: Vec<&str> = r.lines().filter(|l| !l.starts_with('#')).collect();
        assert_eq!(lines.first(), Some(&"local all all trust"));
        assert_eq!(
            lines.last(),
            Some(&"host all all all reject"),
            "the last rule rejects"
        );
        for (i, (role, db, _)) in DB_LOGINS.iter().enumerate() {
            let want = format!("host {db} {role} 172.{}.0.0/16 scram-sha-256", 30 + i);
            assert!(lines.contains(&want.as_str()), "{want}");
            let own: Vec<_> = lines
                .iter()
                .filter(|l| l.contains(&format!(" {role} ")))
                .collect();
            assert_eq!(own.len(), 1, "{role} has exactly its own range");
        }
        assert!(
            !lines
                .iter()
                .any(|l| l.starts_with("host") && l.contains(" sesh ")),
            "no network rule for the superuser"
        );
        assert!(
            !lines
                .iter()
                .any(|l| l.contains(" trust") && l.starts_with("host")),
            "no trust over the network"
        );
        assert_eq!(render(&ranges).unwrap(), r, "stable");
    }

    #[test]
    fn a_missing_or_odd_range_fails_closed_naming_the_network() {
        let none = |n: &str| -> Result<Vec<String>> {
            if n == "paperless-db" {
                Ok(vec![])
            } else {
                ranges(n)
            }
        };
        let e = render(&none).unwrap_err().to_string();
        assert!(
            e.contains("sesh_paperless-db") && e.contains("stay refused"),
            "{e}"
        );
        let broken = |n: &str| -> Result<Vec<String>> {
            if n == "litellm-db" {
                bail!("docker says no")
            } else {
                ranges(n)
            }
        };
        assert!(
            render(&broken)
                .unwrap_err()
                .to_string()
                .contains("sesh_litellm-db")
        );
        let odd = |_: &str| -> Result<Vec<String>> { Ok(vec!["0.0.0.0/0 trust\nhost all".into()]) };
        assert!(render(&odd).is_err(), "nothing but a CIDR reaches the file");
    }

    #[test]
    fn ipv6_ranges_are_accepted() {
        let both = |n: &str| -> Result<Vec<String>> {
            let mut r = ranges(n)?;
            r.push("fd00:1::/64".into());
            Ok(r)
        };
        assert!(render(&both).unwrap().contains("fd00:1::/64 scram-sha-256"));
    }
}
