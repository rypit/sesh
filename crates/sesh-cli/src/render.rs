//! Renders the alias router's config (`litellm.yaml`) from [`Config`]
//! (data-model.md, Rendered router config). Pure: no I/O.
//!
//! Every scalar is written as a JSON string, which is valid YAML, so no
//! value from the config can change the document's structure.

use crate::config::Config;

pub const FILE_NAME: &str = "litellm.yaml";

fn q(s: &str) -> String {
    serde_json::to_string(s).expect("strings always serialize")
}

pub fn litellm_config(config: &Config) -> String {
    let api_key = match &config.inference.api_key_env {
        // `sesh up` copies the variable named by api_key_env into this one.
        Some(_) => "os.environ/SESH_INFERENCE_API_KEY".to_string(),
        None => "none".to_string(),
    };
    let mut out = String::from("# Generated by `sesh` from sesh.toml. Do not edit.\nmodel_list:\n");
    for (alias, model) in &config.aliases {
        out.push_str(&format!(
            "  - model_name: {}\n    litellm_params:\n      model: {}\n      api_base: {}\n      api_key: {}\n      timeout: {}\n",
            q(alias),
            q(&format!("openai/{model}")),
            q(&config.inference.base_url),
            q(&api_key),
            config.inference.timeout_secs,
        ));
    }
    out.push_str(
        "general_settings:\n  master_key: \"os.environ/LITELLM_MASTER_KEY\"\n  database_url: \"os.environ/DATABASE_URL\"\nlitellm_settings:\n  telemetry: false\n",
    );
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn one_entry_per_alias_and_no_wildcards() {
        let mut c = Config::new("http://srv:8080/v1", "qwen3");
        c.aliases.insert("agent-small".into(), "phi".into());
        let y = litellm_config(&c);
        assert_eq!(y.matches("model_name:").count(), 2);
        assert!(y.contains("model_name: \"agent-main\""));
        assert!(y.contains("model: \"openai/qwen3\""));
        assert!(y.contains("model: \"openai/phi\""));
        assert!(y.contains("api_base: \"http://srv:8080/v1\""));
        assert!(!y.contains('*'));
        assert!(y.contains("telemetry: false"));
        assert!(y.contains("master_key: \"os.environ/LITELLM_MASTER_KEY\""));
    }

    #[test]
    fn key_is_an_env_reference_never_a_value() {
        let mut c = Config::new("http://srv/v1", "m");
        assert!(litellm_config(&c).contains("api_key: \"none\""));
        c.inference.api_key_env = Some("INFERENCE_API_KEY".into());
        assert!(litellm_config(&c).contains("api_key: \"os.environ/SESH_INFERENCE_API_KEY\""));
    }

    #[test]
    fn hostile_values_stay_quoted() {
        let c = Config::new("http://srv/v1", "m\"\n  - model_name: evil");
        let y = litellm_config(&c);
        let entries = y
            .lines()
            .filter(|l| l.starts_with("  - model_name:"))
            .count();
        assert_eq!(entries, 1);
        assert!(y.contains(r#"openai/m\"\n  - model_name: evil"#));
    }
}
