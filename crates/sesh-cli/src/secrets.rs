//! `secrets.env`: local service credentials (data-model.md, Secrets).
//!
//! Values are generated from the OS random source, stored with mode 0600
//! in a 0700 directory outside the repository, and never printed: the
//! `Debug` implementation shows key names only.

use anyhow::{Context, Result, bail};
use base64::Engine;
use std::collections::BTreeMap;
use std::fmt;
use std::path::Path;

